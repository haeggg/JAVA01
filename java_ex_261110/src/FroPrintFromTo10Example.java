public class FroPrintFromTo10Example {
    
    public static void main(String[] args) {
        
        for(int i = 1; i<=10; i++){

            System.out.println(i);
            // 세로로 출력됨

        }

        for(int n = 1; n<=10; n++){

            System.out.print(n + " ");
            // 가로로 출력됨
            
        }
    }
}
