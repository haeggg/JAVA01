public class BooleanExample {
    
    public static void main(String[] args){

        // boolean 활용해서 중지, 시작 설정

        boolean stop = true;

        if(stop){
            System.out.println("중지합니다.");
        }
        else{
            System.out.println("시작합니다.");
        }


        boolean start = false;

        if(start){
            System.out.println("중지합니다.");
        }
        else{
            System.out.println("시작합니다.");
        }
    }
}
